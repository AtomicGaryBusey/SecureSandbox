def _duplicate_rejecting_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for name, value in pairs:
        if name in result:
            raise _DecodeViolation("json_duplicate_key")
        result[name] = value
    return result


def _reject_nonfinite(_: str) -> None:
    raise _DecodeViolation("json_nonfinite_number")


def _bounded_json(value: Any) -> None:
    nodes = 0
    pending: list[tuple[Any, int]] = [(value, 0)]
    while pending:
        current, depth = pending.pop()
        nodes += 1
        if nodes > MAX_JSON_NODES:
            raise _DecodeViolation("json_node_limit")
        if depth > MAX_JSON_DEPTH:
            raise _DecodeViolation("json_depth_limit")
        if current is None or isinstance(current, bool):
            continue
        if isinstance(current, int):
            if current < -(2 ** 63) or current > 2 ** 63 - 1:
                raise _DecodeViolation("json_integer_limit")
            continue
        if isinstance(current, float):
            if not math.isfinite(current):
                raise _DecodeViolation("json_nonfinite_number")
            continue
        if isinstance(current, str):
            if len(current.encode("utf-8")) > MAX_STRING_BYTES:
                raise _DecodeViolation("json_string_limit")
            continue
        if isinstance(current, list):
            if len(current) > MAX_CONTAINER_ITEMS:
                raise _DecodeViolation("json_container_limit")
            pending.extend((item, depth + 1) for item in current)
            continue
        if isinstance(current, dict):
            if len(current) > MAX_CONTAINER_ITEMS:
                raise _DecodeViolation("json_container_limit")
            for name, item in current.items():
                if not isinstance(name, str):
                    raise _DecodeViolation("json_key_invalid")
                if len(name.encode("utf-8")) > MAX_IDENTIFIER_BYTES:
                    raise _DecodeViolation("json_key_limit")
                pending.append((item, depth + 1))
            continue
        raise _DecodeViolation("json_type_invalid")


def _decode_line(line: bytes) -> dict[str, Any]:
    if not isinstance(line, bytes):
        raise _DecodeViolation("wire_type_invalid")
    if not line or len(line) > MAX_WIRE_BYTES:
        raise _DecodeViolation("wire_size_invalid")
    if not line.endswith(b"\n") or line.count(b"\n") != 1 or b"\x00" in line:
        raise _DecodeViolation("wire_framing_invalid")
    try:
        text = line[:-1].decode("utf-8", errors="strict")
        value = json.loads(
            text,
            object_pairs_hook=_duplicate_rejecting_object,
            parse_constant=_reject_nonfinite,
        )
    except _DecodeViolation:
        raise
    except (UnicodeDecodeError, ValueError, RecursionError):
        raise _DecodeViolation("json_invalid") from None
    if not isinstance(value, dict):
        raise _DecodeViolation("message_not_object")
    _bounded_json(value)
    return value


def _encode_message(value: Mapping[str, Any]) -> bytes:
    encoded = (json.dumps(
        value, ensure_ascii=False, separators=(",", ":"), sort_keys=True,
        allow_nan=False,
    ) + "\n").encode("utf-8")
    if len(encoded) > MAX_WIRE_BYTES:
        raise ProtocolViolation("outbound_message_too_large")
    return encoded


def _require_identifier(value: Any, code: str) -> str:
    if (not isinstance(value, str)
            or _IDENTIFIER.fullmatch(value) is None
            or len(value.encode("ascii")) > MAX_IDENTIFIER_BYTES):
        raise _DecodeViolation(code)
    return value


def _turn_identifier(value: Any) -> str:
    if not isinstance(value, dict):
        raise _DecodeViolation("turn_shape_invalid")
    unknown = set(value) - {
        "completedAt", "durationMs", "error", "id", "items", "itemsView",
        "rootTurnId", "startedAt", "status",
    }
    if unknown:
        raise _DecodeViolation("turn_shape_invalid")
    return _require_identifier(value.get("id"), "turn_id_invalid")


def _thread_identifier(value: Any) -> str:
    if not isinstance(value, dict):
        raise _DecodeViolation("thread_shape_invalid")
    return _require_identifier(value.get("id"), "thread_id_invalid")


class NativeCodexProtocolFirewall:
    """Construct and validate the only app-server exchange SecureSandbox uses."""

    def __init__(self, *, launch_descriptor: Mapping[str, object]) -> None:
        try:
            authority = native_codex_policy.validate_launch_descriptor(
                launch_descriptor)
        except native_codex_policy.NativeCodexPolicyError:
            raise ValueError("native_codex_launch_authority_invalid") from None
        model = authority["model_id"]
        reasoning_effort = authority["reasoning_effort"]
        if model not in ADMITTED_MODELS:
            raise ValueError("native_codex_model_invalid")
        if reasoning_effort not in ADMITTED_REASONING_EFFORTS:
            raise ValueError("native_codex_reasoning_effort_invalid")
        if authority["cyber_access_program"] != CYBER_ACCESS_PROGRAM:
            raise ValueError("native_codex_cyber_access_program_invalid")
        if (not WORKSPACE.startswith("/")
                or posixpath.normpath(WORKSPACE) != WORKSPACE):
            raise RuntimeError("native_codex_workspace_invalid")
        self._model = model
        self._reasoning_effort = reasoning_effort
        self._launch_descriptor_sha256 = authority["descriptor_sha256"]
        self._phase = _Phase.NEW
        self._next_id = 1
        self._pending_id: int | None = None
        self._pending_kind: str | None = None
        self._codex_home: str | None = None
        self._thread_id: str | None = None
        self._observed_thread_id: str | None = None
        self._turn_id: str | None = None
        self._observed_turn_id: str | None = None
        self._turn_completed_before_response = False
        self._completion_status_before_response: str | None = None
        self._trusted_access_verified = False
        self._interrupt_requested = False
        self._qualified_completion: QualifiedTurnCompletion | None = None

    @property
    def failed(self) -> bool:
        return self._phase is _Phase.FAILED

    @property
    def thread_id(self) -> str | None:
        return self._thread_id

    @property
    def turn_id(self) -> str | None:
        return self._turn_id

    @property
    def qualified_completion(self) -> QualifiedTurnCompletion | None:
        return self._qualified_completion

    @property
    def qualification_authority(self) -> CodexFirewallAuthority | None:
        """Return authority only while the firewall is idle and unviolated."""
        if (self._phase is not _Phase.IDLE
                or self._codex_home is None
                or self._thread_id is None
                or self._turn_id is not None):
            return None
        return CodexFirewallAuthority(
            launch_descriptor_sha256=self._launch_descriptor_sha256,
            model=self._model,
            reasoning_effort=self._reasoning_effort,
            codex_home=self._codex_home,
            thread_id=self._thread_id,
        )

    def _fail(self, code: str) -> None:
        self._phase = _Phase.FAILED
        self._pending_id = None
        self._pending_kind = None
        self._qualified_completion = None
        raise ProtocolViolation(code)

    def _require_phase(self, *allowed: _Phase) -> None:
        if self._phase is _Phase.FAILED:
            raise ProtocolViolation("protocol_firewall_failed")
        if self._phase not in allowed:
            self._fail("protocol_state_invalid")

    def _fixed_request(self, kind: _RequestKind,
                       params: Mapping[str, Any]) -> bytes:
        if not isinstance(kind, _RequestKind):
            self._fail("protocol_request_kind_invalid")
        if self._pending_id is not None:
            self._fail("protocol_request_already_pending")
        identifier = self._next_id
        self._next_id += 1
        self._pending_id = identifier
        self._pending_kind = kind.method
        self._phase = kind.phase
        try:
            return _encode_message({
                "id": identifier,
                "method": kind.method,
                "params": params,
            })
        except Exception:
            self._phase = _Phase.FAILED
            self._pending_id = None
            self._pending_kind = None
            raise

    def initialize(self) -> bytes:
        self._require_phase(_Phase.NEW)
        return self._fixed_request(_RequestKind.INITIALIZE, {
            "clientInfo": {
                "name": "SecureSandbox",
                "title": "SecureSandbox",
                "version": "1.0.0",
            },
            "capabilities": {"experimentalApi": True},
        })

    def start_thread(self) -> bytes:
        self._require_phase(_Phase.INITIALIZED)
        return self._fixed_request(_RequestKind.START_THREAD, {
            "allowProviderModelFallback": False,
            "approvalPolicy": "never",
            "approvalsReviewer": "user",
            "cwd": WORKSPACE,
            "dynamicTools": [],
            "effort": self._reasoning_effort,
            "environments": [],
            "ephemeral": False,
            "experimentalRawEvents": False,
            "model": self._model,
            "modelProvider": MODEL_PROVIDER,
            "runtimeWorkspaceRoots": [WORKSPACE],
            "sandbox": "workspace-write",
            "selectedCapabilityRoots": [],
        })

    def start_turn(self, user_text: str) -> bytes:
        self._require_phase(_Phase.IDLE)
        if not isinstance(user_text, str):
            self._fail("user_text_type_invalid")
        try:
            text_bytes = user_text.encode("utf-8")
        except UnicodeEncodeError:
            self._fail("user_text_invalid")
        if (not text_bytes or len(text_bytes) > MAX_USER_TEXT_BYTES
                or "\x00" in user_text):
            self._fail("user_text_invalid")
        assert self._thread_id is not None
        self._observed_turn_id = None
        self._turn_completed_before_response = False
        self._completion_status_before_response = None
        self._trusted_access_verified = False
        self._interrupt_requested = False
        self._qualified_completion = None
        return self._fixed_request(_RequestKind.START_TURN, {
            "approvalPolicy": "never",
            "approvalsReviewer": "user",
            "cwd": WORKSPACE,
            "cyberAccessProgram": CYBER_ACCESS_PROGRAM,
            "disabledPluginIds": [],
            "effort": self._reasoning_effort,
            "environments": [],
            "input": [{"text": user_text, "text_elements": [], "type": "text"}],
            "model": self._model,
            "runtimeWorkspaceRoots": [WORKSPACE],
            "sandboxPolicy": {
                "excludeSlashTmp": True,
                "excludeTmpdirEnvVar": True,
                "networkAccess": False,
                "type": "workspaceWrite",
                "writableRoots": [WORKSPACE],
            },
            "threadId": self._thread_id,
        })

    def interrupt_turn(self) -> bytes:
        self._require_phase(_Phase.ACTIVE)
        assert self._thread_id is not None and self._turn_id is not None
        self._interrupt_requested = True
        return self._fixed_request(_RequestKind.INTERRUPT_TURN, {
            "threadId": self._thread_id,
            "turnId": self._turn_id,
        })

    def ingest_server_line(self, line: bytes) -> CodexServerEvent | None:
        if self._phase is _Phase.FAILED:
            raise ProtocolViolation("protocol_firewall_failed")
        try:
            message = _decode_line(line)
            keys = set(message)
            if "jsonrpc" in message:
                if message["jsonrpc"] != "2.0":
                    raise _DecodeViolation("jsonrpc_version_invalid")
                keys.remove("jsonrpc")
            if "method" in message:
                if "id" in message:
                    raise _DecodeViolation("server_request_forbidden")
                allowed = {"method", "params", "emittedAtMs"}
                if keys - allowed or not {"method", "params"}.issubset(keys):
                    raise _DecodeViolation("notification_shape_invalid")
                if "emittedAtMs" in message and (
                        not isinstance(message["emittedAtMs"], int)
                        or isinstance(message["emittedAtMs"], bool)
                        or not 0 <= message["emittedAtMs"] <= 2 ** 63 - 1):
                    raise _DecodeViolation("notification_timestamp_invalid")
                return self._accept_notification(message["method"], message["params"])
            if "id" in message:
                if keys not in ({"id", "result"}, {"id", "error"}):
                    raise _DecodeViolation("response_shape_invalid")
                self._accept_response(message)
                return None
            raise _DecodeViolation("message_shape_invalid")
        except _DecodeViolation as error:
            self._fail(str(error))
        raise AssertionError("unreachable")

    def _accept_response(self, message: Mapping[str, Any]) -> None:
        identifier = message.get("id")
        if (not isinstance(identifier, int) or isinstance(identifier, bool)
                or identifier != self._pending_id
                or self._pending_kind is None):
            raise _DecodeViolation("response_id_invalid")
        if "error" in message:
            raise _DecodeViolation("server_response_error")
        result = message.get("result")
        kind = self._pending_kind
        if kind == "initialize":
            if self._phase is not _Phase.INITIALIZE_PENDING or not isinstance(result, dict):
                raise _DecodeViolation("initialize_response_invalid")
            if (set(result) != {
                    "codexHome", "platformFamily", "platformOs", "userAgent"}
                    or not isinstance(result["userAgent"], str)
                    or not result["userAgent"].startswith(
                        f"Codex Desktop/{PINNED_APP_SERVER_VERSION} (")
                    or not result["userAgent"].endswith(
                        "(SecureSandbox; 1.0.0)")
                    or result["platformFamily"] != "unix"
                    or result["platformOs"] != "linux"
                    or not isinstance(result["codexHome"], str)
                    or _CODEX_HOME.fullmatch(result["codexHome"]) is None):
                raise _DecodeViolation("initialize_identity_invalid")
            self._codex_home = result["codexHome"]
            self._phase = _Phase.INITIALIZED
        elif kind == "thread/start":
            if self._phase is not _Phase.THREAD_PENDING:
                raise _DecodeViolation("thread_response_invalid")
            self._accept_thread_response(result)
        elif kind == "turn/start":
            if self._phase is not _Phase.TURN_PENDING:
                raise _DecodeViolation("turn_response_invalid")
            self._accept_turn_response(result)
        elif kind == "turn/interrupt":
            if self._phase not in {
                    _Phase.INTERRUPT_PENDING,
                    _Phase.INTERRUPT_PENDING_COMPLETED} or result != {}:
                raise _DecodeViolation("interrupt_response_invalid")
            if self._phase is _Phase.INTERRUPT_PENDING_COMPLETED:
                self._finish_turn()
            else:
                self._phase = _Phase.ACTIVE
        else:
            raise _DecodeViolation("response_method_invalid")
        self._pending_id = None
        self._pending_kind = None

    def _accept_thread_response(self, result: Any) -> None:
        if not isinstance(result, dict):
            raise _DecodeViolation("thread_response_invalid")
        if set(result) != _THREAD_RESPONSE_FIELDS:
            raise _DecodeViolation("thread_response_shape_invalid")
        if (result["activePermissionProfile"] is not None
                or result["approvalPolicy"] != "never"
                or result["approvalsReviewer"] != "user"
                or result["cwd"] != WORKSPACE
                or result["disabledPluginIds"] != []
                or result["instructionSources"] != []
                or result["model"] != self._model
                or result["modelProvider"] != MODEL_PROVIDER
                or result["reasoningEffort"] != self._reasoning_effort
                or result["runtimeWorkspaceRoots"] != [WORKSPACE]
                or result["multiAgentMode"] != "explicitRequestOnly"
                or result["serviceTier"] is not None):
            raise _DecodeViolation("thread_policy_readback_invalid")
        sandbox = result["sandbox"]
        if (not isinstance(sandbox, dict)
                or set(sandbox) != {
                    "excludeSlashTmp", "excludeTmpdirEnvVar", "networkAccess",
                    "type", "writableRoots",
                }
                or sandbox["type"] != "workspaceWrite"
                or sandbox["networkAccess"] is not False
                or sandbox["writableRoots"] != [WORKSPACE]
                or sandbox["excludeSlashTmp"] is not True
                or sandbox["excludeTmpdirEnvVar"] is not True):
            raise _DecodeViolation("thread_sandbox_readback_invalid")
        thread_id = _thread_identifier(result["thread"])
        self._require_thread_metadata(result["thread"])
        if (self._observed_thread_id is not None
                and self._observed_thread_id != thread_id):
            raise _DecodeViolation("thread_id_mismatch")
        self._thread_id = thread_id
        self._phase = _Phase.IDLE

    def _accept_turn_response(self, result: Any) -> None:
        if not isinstance(result, dict) or set(result) != {"turn"}:
            raise _DecodeViolation("turn_response_shape_invalid")
        turn_id = _turn_identifier(result["turn"])
        if result["turn"].get("status") != "inProgress":
            raise _DecodeViolation("turn_start_status_invalid")
        if self._observed_turn_id is not None and self._observed_turn_id != turn_id:
            raise _DecodeViolation("turn_id_mismatch")
        self._turn_id = turn_id
        if self._turn_completed_before_response:
            if self._completion_status_before_response != "completed":
                raise _DecodeViolation("turn_completion_status_invalid")
            if self._trusted_access_verified:
                self._qualify_and_finish()
            else:
                self._phase = _Phase.AWAITING_VERIFICATION
        else:
            self._phase = _Phase.ACTIVE

    def _accept_notification(self, method: Any, params: Any) -> CodexServerEvent:
        if not isinstance(method, str) or method not in _NOTIFICATIONS:
            raise _DecodeViolation("server_notification_forbidden")
        if not isinstance(params, dict):
            raise _DecodeViolation("notification_params_invalid")
        spec = _NOTIFICATIONS[method]
        if set(params) - spec.allowed or not spec.required.issubset(params):
            raise _DecodeViolation("notification_params_invalid")
        if (method == "remoteControl/status/changed"
                and self._phase in {_Phase.INITIALIZED, _Phase.THREAD_PENDING}):
            pass
        elif self._phase not in _THREAD_PHASES:
            raise _DecodeViolation("notification_state_invalid")
        if spec.turn_bound and self._phase not in _TURN_PHASES:
            raise _DecodeViolation("notification_state_invalid")

        if method == "thread/started":
            observed = _thread_identifier(params["thread"])
            self._require_thread_metadata(params["thread"])
            if self._thread_id is not None and observed != self._thread_id:
                raise _DecodeViolation("thread_id_mismatch")
            if (self._observed_thread_id is not None
                    and observed != self._observed_thread_id):
                raise _DecodeViolation("thread_id_mismatch")
            self._observed_thread_id = observed
        elif method == "remoteControl/status/changed":
            if (params["status"] != "disabled"
                    or params.get("environmentId") is not None
                    or not isinstance(params["serverName"], str)
                    or not params["serverName"]
                    or not isinstance(params["installationId"], str)
                    or not params["installationId"]):
                raise _DecodeViolation("remote_control_not_disabled")
        else:
            observed_thread = _require_identifier(
                params.get("threadId"), "thread_id_invalid")
            if self._thread_id is None or observed_thread != self._thread_id:
                raise _DecodeViolation("thread_id_mismatch")

        if spec.turn_bound:
            if method in {"turn/started", "turn/completed"}:
                observed_turn = _turn_identifier(params["turn"])
            else:
                observed_turn = _require_identifier(
                    params.get("turnId"), "turn_id_invalid")
            if self._turn_id is not None and observed_turn != self._turn_id:
                raise _DecodeViolation("turn_id_mismatch")
            if (self._observed_turn_id is not None
                    and observed_turn != self._observed_turn_id):
                raise _DecodeViolation("turn_id_mismatch")
            self._observed_turn_id = observed_turn

        if method == "model/verification":
            if (params["verifications"] != ["trustedAccessForCyber"]
                    or self._trusted_access_verified):
                raise _DecodeViolation("trusted_access_verification_invalid")
            self._trusted_access_verified = True
            if self._phase is _Phase.AWAITING_VERIFICATION:
                self._qualify_and_finish()
        elif method == "turn/completed":
            status = params["turn"].get("status")
            expected = "interrupted" if self._interrupt_requested else "completed"
            if status != expected:
                raise _DecodeViolation("turn_completion_status_invalid")
            if self._phase is _Phase.TURN_PENDING:
                self._turn_completed_before_response = True
                self._completion_status_before_response = status
            elif self._phase is _Phase.INTERRUPT_PENDING:
                self._phase = _Phase.INTERRUPT_PENDING_COMPLETED
            elif status == "completed":
                if self._trusted_access_verified:
                    self._qualify_and_finish()
                else:
                    self._phase = _Phase.AWAITING_VERIFICATION
            else:
                self._finish_turn()
        return CodexServerEvent(method=method, params=params)

    def _require_thread_metadata(self, value: Mapping[str, Any]) -> None:
        if (set(value) != _THREAD_METADATA_FIELDS
                or value["cliVersion"] != PINNED_APP_SERVER_VERSION
                or value["cwd"] != WORKSPACE
                or value["environments"] != []
                or value["ephemeral"] is not False
                or value["model"] != self._model
                or value["modelProvider"] != MODEL_PROVIDER
                or value["reasoningEffort"] != self._reasoning_effort):
            raise _DecodeViolation("thread_metadata_readback_invalid")
        thread_id = _thread_identifier(value)
        if (value["agentNickname"] is not None
                or value["agentRole"] is not None
                or value["canAcceptDirectInput"] is not True
                or (value["daybreakEnabled"] is not None
                    and not isinstance(value["daybreakEnabled"], bool))
                or value["extra"] is not None
                or value["forkedFromId"] is not None
                or value["gitInfo"] is not None
                or value["historyMode"] != "paginated"
                or value["name"] is not None
                or value["originator"] != "Codex Desktop"
                or value["parentThreadId"] is not None
                or value["preview"] != ""
                or value["projectId"] is not None
                or value["section"] is not None
                or value["sectionEnteredAt"] is not None
                or value["sessionId"] != thread_id
                or value["source"] != "vscode"
                or value["status"] != {"type": "idle"}
                or value["threadSource"] is not None
                or value["turns"] != []):
            raise _DecodeViolation("thread_metadata_readback_invalid")
        timestamps = (
            value["createdAt"], value["updatedAt"], value["recencyAt"])
        if (any(not isinstance(timestamp, int)
                or isinstance(timestamp, bool)
                or not 0 <= timestamp <= 2 ** 63 - 1
                for timestamp in timestamps)
                or not timestamps[0] <= timestamps[1]
                or not timestamps[0] <= timestamps[2]):
            raise _DecodeViolation("thread_metadata_readback_invalid")
        path = value["path"]
        if (self._codex_home is None
                or not isinstance(path, str)
                or posixpath.normpath(path) != path
                or not path.startswith(self._codex_home + "/sessions/")
                or not path.endswith(".jsonl")):
            raise _DecodeViolation("thread_metadata_readback_invalid")

    def _qualify_and_finish(self) -> None:
        if (self._thread_id is None or self._turn_id is None
                or not self._trusted_access_verified
                or self._interrupt_requested):
            raise _DecodeViolation("qualified_completion_invalid")
        self._qualified_completion = QualifiedTurnCompletion(
            thread_id=self._thread_id,
            turn_id=self._turn_id,
            model=self._model,
            launch_descriptor_sha256=self._launch_descriptor_sha256,
            cyber_access_program=CYBER_ACCESS_PROGRAM,
            verifications=("trustedAccessForCyber",),
        )
        self._finish_turn()

    def _finish_turn(self) -> None:
        self._phase = _Phase.IDLE
        self._turn_id = None
        self._observed_turn_id = None
        self._turn_completed_before_response = False
        self._completion_status_before_response = None
        self._trusted_access_verified = False
        self._interrupt_requested = False


