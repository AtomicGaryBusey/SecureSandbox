#!/usr/bin/env python3
"""Fail-closed client boundary for the pinned Codex 0.166 app-server.

The native Codex launcher exposes a stdio JSON-RPC transport.  That transport
is a privileged control plane: Codex 0.166 includes client methods such as
``process/spawn`` and ``thread/shellCommand`` that intentionally execute
without the thread sandbox.  Human text and terminal bytes must therefore
never be forwarded to app-server directly.

This module deliberately has no generic request builder.  It emits only the
fixed initialize, thread/start, turn/start, and turn/interrupt messages used by
SecureSandbox.  Every turn restates the non-escalating sandbox and Daybreak
policy.  Incoming messages are bounded, duplicate-key rejecting, stateful, and
limited to the exact output-only notification subset consumed by the terminal
client.

Protocol names and shapes are pinned to the schema generated by:

    codex-cli 0.166.0 app-server generate-json-schema --experimental

The live acceptance suite must still prove the resolved Linux sandbox and its
PID/user/mount/network namespace boundary.  This parser cannot prove vendor
runtime behavior by itself.
"""

