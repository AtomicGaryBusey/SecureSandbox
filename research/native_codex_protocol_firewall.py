class ProtocolViolation(RuntimeError):
    """A stable, non-reflecting failure at the app-server boundary."""

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


class _DecodeViolation(ValueError):
    pass


class _Phase(Enum):
    NEW = auto()
    INITIALIZE_PENDING = auto()
    INITIALIZED = auto()
    THREAD_PENDING = auto()
    IDLE = auto()
    TURN_PENDING = auto()
    ACTIVE = auto()
    INTERRUPT_PENDING = auto()
    INTERRUPT_PENDING_COMPLETED = auto()
    AWAITING_VERIFICATION = auto()
    FAILED = auto()


class _RequestKind(Enum):
    INITIALIZE = ("initialize", _Phase.INITIALIZE_PENDING)
    START_THREAD = ("thread/start", _Phase.THREAD_PENDING)
    START_TURN = ("turn/start", _Phase.TURN_PENDING)
    INTERRUPT_TURN = ("turn/interrupt", _Phase.INTERRUPT_PENDING)

    @property
    def method(self) -> str:
        return self.value[0]

    @property
    def phase(self) -> _Phase:
        return self.value[1]


